"use client";

import { zodResolver } from "@hookform/resolvers/zod";
import { useSignAndSendTransaction } from "@privy-io/react-auth/solana";
import { useClient } from "@solana/react";
import {
  address,
  appendTransactionMessageInstruction,
  compileTransaction,
  createNoopSigner,
  createTransactionMessage,
  getBase58Decoder,
  getTransactionEncoder,
  pipe,
  setTransactionMessageFeePayer,
  setTransactionMessageLifetimeUsingBlockhash,
} from "@solana/kit";
import { Save } from "lucide-react";
import { useState } from "react";
import { useForm } from "react-hook-form";
import { z } from "zod";
import { SuccessAlert } from "@/components/commons/SuccessAlert";
import { explorerTxUrl } from "@/components/utils";
import { Button } from "@/components/ui/button";
import {
  Card,
  CardContent,
  CardDescription,
  CardFooter,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { AppClient } from "@/lib/solana";
import { useWalletAddress } from "../hooks";

const favoritesSchema = z.object({
  number: z
    .string()
    .trim()
    .min(1, "Enter a number")
    .regex(/^\d+$/, "Use a whole number"),
  color: z.string().trim().min(1, "Enter a color"),
  hobbies: z.string().trim().min(1, "Enter at least one hobby"),
});

type FavoritesSchemaType = z.infer<typeof favoritesSchema>;

export const Write = () => {
  const { wallet, noWalletFallback } = useWalletAddress();

  const client = useClient<AppClient>();
  const { signAndSendTransaction } = useSignAndSendTransaction();

  const [signature, setSignature] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [isSending, setIsSending] = useState(false);

  const {
    register,
    handleSubmit,
    formState: { errors },
  } = useForm<FavoritesSchemaType>({
    resolver: zodResolver(favoritesSchema),
    defaultValues: { number: "", color: "", hobbies: "" },
  });

  if (!wallet) return noWalletFallback;

  const onSubmit = async (values: FavoritesSchemaType) => {
    setSignature(null);
    setError(null);
    setIsSending(true);

    const walletAddress = address(wallet.address);

    try {
      const { value: latestBlockhash } = await client.rpc
        .getLatestBlockhash()
        .send();

      // Instruction from the plugin generated by Codama (lib/generated/favorites)
      const setFavoritesIx = await client.favorites.instructions.setFavorites({
        signer: createNoopSigner(walletAddress),
        number: BigInt(values.number),
        color: values.color,
        hobbies: values.hobbies
          .split(",")
          .map((hobby) => hobby.trim())
          .filter(Boolean),
      });

      const setFavoritesTx = pipe(
        createTransactionMessage({ version: 0 }),
        (tx) => setTransactionMessageFeePayer(walletAddress, tx),
        (tx) =>
          setTransactionMessageLifetimeUsingBlockhash(latestBlockhash, tx), // Set recent blockhash
        (tx) => appendTransactionMessageInstruction(setFavoritesIx, tx),
        (tx) => compileTransaction(tx), // Compile the transaction
        (tx) => new Uint8Array(getTransactionEncoder().encode(tx)), // Finally encode the transaction
      );

      const setFavoritesTxResult = await signAndSendTransaction({
        transaction: setFavoritesTx,
        wallet,
        chain: "solana:devnet",
      });

      setSignature(getBase58Decoder().decode(setFavoritesTxResult.signature));
    } catch (e) {
      setError(e instanceof Error ? e.message : "Transaction failed");
    } finally {
      setIsSending(false);
    }
  };

  return (
    <Card className="w-full max-w-2xl">
      <form
        className="flex flex-col gap-4"
        onSubmit={handleSubmit(onSubmit)}
        noValidate
      >
        <CardHeader>
          <CardTitle>Set favorites</CardTitle>
          <CardDescription>
            Save your favorite number, color and hobbies on devnet
          </CardDescription>
        </CardHeader>
        <CardContent className="flex flex-col gap-4">
          {signature && (
            <SuccessAlert
              title="Transaction sent"
              href={explorerTxUrl(signature)}
            />
          )}
          {error && (
            <p
              role="alert"
              className="rounded-lg border border-destructive/50 p-3 text-sm text-destructive"
            >
              {error}
            </p>
          )}
          <div className="flex flex-col gap-2">
            <Label htmlFor="number">Number</Label>
            <Input
              id="number"
              type="text"
              inputMode="numeric"
              placeholder="7"
              autoComplete="off"
              aria-invalid={!!errors.number}
              aria-describedby={errors.number ? "number-error" : undefined}
              className="tabular-nums"
              {...register("number")}
            />
            {errors.number && (
              <p
                id="number-error"
                role="alert"
                className="text-sm text-destructive"
              >
                {errors.number.message}
              </p>
            )}
          </div>
          <div className="flex flex-col gap-2">
            <Label htmlFor="color">Color</Label>
            <Input
              id="color"
              type="text"
              placeholder="Blue"
              autoComplete="off"
              aria-invalid={!!errors.color}
              aria-describedby={errors.color ? "color-error" : undefined}
              {...register("color")}
            />
            {errors.color && (
              <p
                id="color-error"
                role="alert"
                className="text-sm text-destructive"
              >
                {errors.color.message}
              </p>
            )}
          </div>
          <div className="flex flex-col gap-2">
            <Label htmlFor="hobbies">Hobbies</Label>
            <Input
              id="hobbies"
              type="text"
              placeholder="Reading, chess, hiking"
              autoComplete="off"
              aria-invalid={!!errors.hobbies}
              aria-describedby={errors.hobbies ? "hobbies-error" : undefined}
              {...register("hobbies")}
            />
            {errors.hobbies && (
              <p
                id="hobbies-error"
                role="alert"
                className="text-sm text-destructive"
              >
                {errors.hobbies.message}
              </p>
            )}
          </div>
        </CardContent>
        <CardFooter>
          <Button
            type="submit"
            disabled={isSending}
            className="w-full sm:w-auto"
          >
            <Save />
            {isSending ? "Saving…" : "Set favorites"}
          </Button>
        </CardFooter>
      </form>
    </Card>
  );
};
